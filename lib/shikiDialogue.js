export const EMOTE = { opening: "❗", capture: "♪", setback: "💢", tease: "💭", win: "✨", lose: "💧", draw: "🍵" };

export function opponentArt(name) { return "/shiki-duel/arena/" + (V[name]?.art || "amber") + ".webp"; }
// Câu thoại ngẫu nhiên theo tâm trạng, tránh lặp lại câu vừa nói
export function opponentLine(name, mood, prev) {
  const pool = V[name]?.[mood] || V.Amber[mood] || [""];
  const options = pool.length > 1 ? pool.filter((l) => l !== prev) : pool;
  return options[Math.floor(Math.random() * options.length)];
}

// Tâm trạng của đối thủ sau một nước đi
export function reactionFor(move) {
  if (!move) return "opening";
  if (move.flips.length) return move.who === "me" ? "setback" : "capture";
  return "tease";
}
